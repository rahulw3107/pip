import random

def fermat(n, k=5):
    if n < 2:
        return False
    if n in (2, 3):
        return True
    if n % 2 == 0:
        return False
    for _ in range(k):
        a = random.randint(2, n - 2)
        if pow(a, n - 1, n) != 1:
            return False
    return True

n = int(input("Enter number: "))
print("Probably Prime" if fermat(n) else "Composite")
